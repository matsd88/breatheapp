# Output directory
OUTPUT_DIR = Path("output")

# Progress tracking
progress_file = Path("download_progress.json")


def load_progress():
    """Load progress from file to resume interrupted downloads."""
    if progress_file.exists():
        with open(progress_file) as f:
            return json.load(f)
    return {"completed": [], "failed": []}


def save_progress(progress):
    """Save progress to file."""
    with open(progress_file, "w") as f:
        json.dump(progress, f, indent=2)


def _do_download(video_id: str, output_dir: Path, result_queue: Queue):
    """Worker function that runs in subprocess with hard timeout."""
    from pytubefix import YouTube

    video_dir = output_dir / video_id
    video_dir.mkdir(parents=True, exist_ok=True)

    url = f"https://www.youtube.com/watch?v={video_id}"
    errors = []

    try:
        yt = YouTube(url)
    except Exception as e:
        result_queue.put((False, f"Failed to load: {str(e)[:50]}"))
        return

    # Download audio
    audio_path = video_dir / "audio.m4a"
    if not audio_path.exists():
        try:
            audio_stream = yt.streams.filter(only_audio=True, mime_type='audio/mp4').order_by('abr').desc().first()
            if audio_stream:
                audio_stream.download(output_path=str(video_dir), filename='audio.m4a')
            else:
                errors.append("No audio stream")
        except Exception as e:
            errors.append(f"Audio: {str(e)[:50]}")

    # Download video
    video_path = video_dir / "video.mp4"
    if not video_path.exists():
        try:
            video_stream = yt.streams.filter(progressive=True, file_extension='mp4').order_by('resolution').desc().first()
            if video_stream:
                video_stream.download(output_path=str(video_dir), filename='video.mp4')
            else:
                errors.append("No video stream")
        except Exception as e:
            errors.append(f"Video: {str(e)[:50]}")

    # Download thumbnail
    thumb_path = video_dir / "thumb.jpg"
    if not thumb_path.exists():
        try:
            thumb_url = f"https://img.youtube.com/vi/{video_id}/mqdefault.jpg"
            urllib.request.urlretrieve(thumb_url, str(thumb_path))
        except Exception as e:
            errors.append(f"Thumb: {str(e)[:50]}")

    success = audio_path.exists() and video_path.exists() and thumb_path.exists()
    result_queue.put((success, "; ".join(errors) if errors else ""))


def download_video(video_id: str, progress: dict, timeout: int = 60) -> tuple:
    """
    Download audio, video, and thumbnail for a single video ID using pytubefix.
    Uses multiprocessing for hard timeout. Returns (video_id, success, error_message)
    """
    if video_id in progress["completed"]:
        return video_id, True, "Already completed"

    result_queue = Queue()
    proc = Process(target=_do_download, args=(video_id, OUTPUT_DIR, result_queue))
    proc.start()
    proc.join(timeout=timeout)

    if proc.is_alive():
        proc.terminate()
        proc.join(timeout=5)
        if proc.is_alive():
            proc.kill()
        if video_id not in progress["failed"]:
            progress["failed"].append(video_id)
        return video_id, False, "Timed out"

    try:
        success, error = result_queue.get_nowait()
    except Empty:
        success, error = False, "No result from worker"

    if success:
        progress["completed"].append(video_id)
        if video_id in progress["failed"]:
            progress["failed"].remove(video_id)
    elif video_id not in progress["failed"]:
        progress["failed"].append(video_id)

    return video_id, success, error


